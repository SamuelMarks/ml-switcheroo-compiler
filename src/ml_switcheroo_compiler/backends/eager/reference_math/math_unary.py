@global_eager_registry.register("Erf")
def _np_erf(
    backend_module: BackendModuleProtocol | types.ModuleType | None, *args: BackendArg, **kwargs: BackendArg
) -> BackendArg:
    """Execute the eager np erf operation on the active backend array.

    Args:
        backend_module (BackendModuleProtocol | types.ModuleType | None):
            Input `backend_module` argument (backend module).
        *args (BackendArg): Positional args.
        **kwargs (BackendArg): Keyword args.

    Returns:
            tuple[int, ...]: Computed `tuple[int, ...]` output.
    """
    import math

    x = args[0]
    if adapt_backend_module(backend_module).has_symbol("asarray"):
        x = adapt_backend_module(backend_module).require_symbol("asarray")(x)
    if adapt_backend_module(x).get_symbol("ndim", 0) == 0:
        return math.erf(float(coerce_float(x)))
    return adapt_backend_module(backend_module).require_symbol("vectorize")(math.erf)(x)


