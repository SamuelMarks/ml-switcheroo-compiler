@global_eager_registry.register("Logit")
def _np_logit(
    backend_module: BackendModuleProtocol | types.ModuleType | None,
    x: BackendArg,
    eps: BackendArg = None,
    *args: BackendArg,
    **kwargs: BackendArg,
) -> BackendArg:
    """Execute the eager np logit operation on the active backend array.

    Args:
        backend_module (BackendModuleProtocol | types.ModuleType | None):
            Input `backend_module` argument (backend module).
        x (BackendArg): Input `x` argument (x).
        eps (BackendArg): Input `eps` argument (eps).
        *args (BackendArg): Positional args.
        **kwargs (BackendArg): Keyword args.

    Returns:
            tuple[int, ...]: Computed `tuple[int, ...]` output.
    """
    arr_mod = _resolve_eager_mod(backend_module)
    from ml_switcheroo_compiler.backends.eager_registry import coerce_numeric

    x_num = coerce_numeric(x)
    with adapt_backend_module(arr_mod).require_symbol("errstate")(divide="ignore"):
        return adapt_backend_module(backend_module).require_symbol("log")(x_num / (1.0 - x_num))


