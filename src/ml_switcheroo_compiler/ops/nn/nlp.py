@register_op("CtcLoss")
class CtcLoss(OpDef):
    """Operator definition for Connectionist Temporal Classification (CTC) Loss."""

    op_name = "CtcLoss"

    def infer_shape(self, labels: EagerTensorProtocol, logits: EagerTensorProtocol, label_length: EagerTensorProtocol, logit_length: EagerTensorProtocol, **kwargs: TensorOrScalar) -> TensorOrScalar:
        """Infers the output shape for the CTC loss operation.

        Args:
            labels: A tensor of target labels.
            logits: A tensor of predicted logits.
            label_length: A tensor representing the lengths of the labels.
            logit_length: A tensor representing the lengths of the logits.
            kwargs: Additional keyword arguments.

        Returns:
            A tuple representing the inferred output shape.
        """
        # logits: (T, N, C) if time_major else (N, T, C)
        time_major = kwargs.get("logits_time_major", True)
        if hasattr(logits, "shape"):
            if len(logits.shape) == 3:
                batch = logits.shape[1] if time_major else logits.shape[0]
                return (batch,)
            elif len(logits.shape) == 2:
                return (1,)
        return (1,)
